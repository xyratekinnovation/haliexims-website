function toSlug(title: string): string {
  return title
    .normalize("NFKD")
    .toLowerCase()
    .replace(/¼/g, "1-4")
    .replace(/⅜/g, "3-8")
    .replace(/[×]/g, "x")
    .replace(/[–—−]/g, "-")
    .replace(/["'`´""'']/g, "")
    .replace(/[()[\]{}]/g, "")
    .replace(/&/g, "and")
    .replace(/:/g, "-")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

function sikaProduct(input: {
  title: string;
  badge: string;
  shortDescription: string;
  description: string;
  specifications: { label: string; value: string }[];
  features: string[];
  applications: string[];
}): CatalogProduct {
  const id = toSlug(input.title);
  const image = toProductImageFileName(input.title);
  return {
    id,
    slug: id,
    categorySlug: CHEMICALS,
    sectionSlug: SECTION,
    title: input.title,
    badge: input.badge,
    shortDescription: input.shortDescription,
    description: input.description,
    image,
    gallery: [image, image, image],
    specifications: input.specifications,
    specPreview: input.specifications.slice(0, 3).map((s) => `${s.label}: ${s.value}`),
    features: input.features,
    applications: input.applications,
    packaging: exportPackaging,
    relatedProductIds: [],
  };
}

